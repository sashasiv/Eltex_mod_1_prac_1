// child.h
#ifndef CHILD_H
#define CHILD_H

/* Запустить цикл приёма файлов в дочернем процессе.

   rfd — дескриптор, из которого ребёнок ЧИТАЕТ сообщения от родителя
         (HEADER, DATA, END).
   wfd — дескриптор, в который ребёнок ПИШЕТ сообщения родителю
         (READY, DONE).

   Функция не возвращает управление: завершает процесс через _exit()
   при получении MSG_END, при EOF на rfd (родитель закрыл канал)
   или при фатальной ошибке протокола.

   Вызывается ТОЛЬКО в дочернем процессе после fork(). */
void child_run(int rfd, int wfd);

#endif