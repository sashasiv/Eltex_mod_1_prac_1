#ifndef CONFIG_H
#define CONFIG_H

#include <stddef.h>

 /* ---------------------------------------------------------------------------
  * 1. Идентификаторы ресурсов IPC
  *
  *    System V использует числовые ключи (key_t).
  *    POSIX использует имена в пространстве /dev/shm.
  *
  *    Ключи и имена выбраны произвольно, но должны совпадать у producer
  *    и consumer.
  * ------------------------------------------------------------------------- */

  /* --- System V --- */
#define CFG_SV_SHM_KEY      0x1234      /* ключ сегмента разделяемой памяти */
#define CFG_SV_SEM_KEY      0x1235      /* ключ набора семафоров          */

/* --- POSIX --- */
#define CFG_PX_SHM_NAME     "/prod_cons_shm"   /* имя объекта shm_open   */
#define CFG_PX_SEM_NAME     "/prod_cons_sem"   /* имя объекта sem_open   */


/* --- 2. Раскладка разделяемой памяти -------------------------------------- */
/*
 *   [0]                    : done_flag_t producer_done  (0 = идёт генерация)
 *   выравнивание до BlockHdr
 *   далее                  : блоки односвязного списка
 *
 *   BlockHdr.next — СМЕЩЕНИЕ от начала сегмента, не указатель:
 *   разные процессы видят сегмент по разным адресам. next == 0 — конец.
 */

 /* Полный размер сегмента разделяемой памяти, байт. */
#define CFG_SHM_SIZE        (64 * 1024)

/* Тип полезной нагрузки одного элемента блока. */
typedef int payload_t;

/* Заголовок блока. Только POD-типы фиксированного размера: структура
 * попадает в разделяемую память как есть. */
typedef struct {
    int count;   /* число элементов в блоке; 0 = блок обработан/пуст */
    int next;    /* смещение следующего блока от начала сегмента; 0 = конец */
} BlockHdr;

/* Служебное поле в начале сегмента. */
typedef int done_flag_t;
#define CFG_DONE_OFFSET     0           /* смещение producer_done */


/* ---------------------------------------------------------------------------
 * 3. Лимиты на данные
 * ------------------------------------------------------------------------- */

 /* Минимальное и максимальное число элементов в одном блоке.
  * Производитель выбирает n равномерно из [MIN, MAX]. */
#define CFG_BLOCK_MIN_ELEMS 1
#define CFG_BLOCK_MAX_ELEMS 1000

  /* Диапазон генерируемых чисел: [MIN, MAX] включительно. */
#define CFG_VALUE_MIN       (-10000)
#define CFG_VALUE_MAX       (10000)


/* ---------------------------------------------------------------------------
 * 4. Тайминги (микросекунды)
 * ------------------------------------------------------------------------- */

 /* Пауза производителя между генерациями блоков. */
#define CFG_PRODUCER_SLEEP_US   (100 * 1000)    /* 100 мс */

/* Пауза потребителя после обработки одного блока. */
#define CFG_CONSUMER_WORK_US    (200 * 1000)    /* 200 мс */

/* Пауза потребителя, когда необработанных блоков нет. */
#define CFG_CONSUMER_IDLE_US    (300 * 1000)    /* 300 мс */


/* ---------------------------------------------------------------------------
 * 5. Коды возврата и служебные значения
 * ------------------------------------------------------------------------- */

 /* Оффсет 0 зарезервирован под producer_done, поэтому «нет блока»
  * тоже обозначается 0 — это безопасно, т.к. первый блок всегда
  * лежит по смещению first_block_offset() > 0. */
#define CFG_OFFSET_NONE     0

  /* Коды завершения процессов. */
#define CFG_EXIT_OK         0
#define CFG_EXIT_OPEN_FAIL  1
#define CFG_EXIT_RUNTIME    2

/* --- 6. Отладка (включается -DCFG_DEBUG при сборке) ----------------------- */

#ifdef CFG_DEBUG
#  include <stdio.h>
#  define CFG_LOG(...)      fprintf(stderr, __VA_ARGS__)
#else
#  define CFG_LOG(...)      ((void)0)
#endif

/* --- 7. Вычисляемые константы раскладки ----------------------------------- */
/* Следствия договорённостей выше, а не независимые настройки. */

/* Размер служебной области в начале сегмента. */
/* --- 7. Вычисляемые константы раскладки (ВОЗВРАЩАЕМ) --- */

static inline size_t cfg_header_area_size(void)
{
    size_t raw = sizeof(done_flag_t);
    size_t align = sizeof(BlockHdr);
    return (raw + align - 1) / align * align;
}

static inline size_t cfg_first_block_offset(void)
{
    return cfg_header_area_size();
}

static inline payload_t* cfg_block_body(void* base, size_t block_off)
{
    return (payload_t*)((char*)base + block_off + sizeof(BlockHdr));
}

static inline size_t cfg_block_size(int count)
{
    return sizeof(BlockHdr) + (size_t)count * sizeof(payload_t);
}
#endif /* CONFIG_H */